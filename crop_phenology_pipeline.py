import pandas as pd
import geopandas as gpd
import numpy as np
import matplotlib.pyplot as plt

# 1. Load your real farm boundary shapes
my_farms = gpd.read_file("kwara_farm_boundaries.geojson")

# 2. Define the months of the West African growing season
months = ['May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov']

# 3. Simulate a time-series satellite dataset for your specific fields
# Your background in Ag shines here: crops grow green, peak, and then dry out at harvest!
np.random.seed(42)
time_series_data = []

for idx, row in my_farms.iterrows():
    field_id = row.get('id', idx + 1) # Grabs your QGIS ID or uses the row index

    # Base crop growth trajectories
    if idx % 2 == 0:
        # Field A: Normal, healthy crop development curve
        base_ndvi = [0.18, 0.35, 0.68, 0.82, 0.75, 0.42, 0.22]
    else:
        # Field B: Suffers a sudden mid-season drop (e.g., drought anomaly or pest attack)
        base_ndvi = [0.18, 0.32, 0.45, 0.40, 0.35, 0.25, 0.18]

    # Add a tiny bit of random natural variance to make it realistic
    final_ndvi = [val + np.random.uniform(-0.03, 0.03) for val in base_ndvi]

    # Save the results for each month
    for m_idx, month in enumerate(months):
        time_series_data.append({
            "Field_ID": f"Farm_{field_id}",
            "Month": month,
            "NDVI_Health": round(final_ndvi[m_idx], 2)
        })

# 4. Convert the results into a clean Pandas DataFrame
df_timeseries = pd.DataFrame(time_series_data)
print("--- AUTOMATED SATELLITE EXTRACT DATA ---")
print(df_timeseries.head(10))

# 5. GENERATE THE TIME-SERIES CROP HEALTH GRAPH
plt.figure(figsize=(10, 6))

for field in df_timeseries["Field_ID"].unique():
    field_df = df_timeseries[df_timeseries["Field_ID"] == field]
    plt.plot(field_df["Month"], field_df["NDVI_Health"], marker='o', linewidth=2, label=field)

plt.title("Satellite Earth Observation: Multi-Temporal Crop Phenology Curves (Kwara State)", fontsize=12, pad=15)
plt.xlabel("Growing Season Timeline", fontsize=10)
plt.ylabel("Vegetation Vigor Index (Mean NDVI)", fontsize=10)
plt.grid(True, linestyle="--", alpha=0.5)
plt.ylim(0, 1.0)
plt.legend()
plt.show()