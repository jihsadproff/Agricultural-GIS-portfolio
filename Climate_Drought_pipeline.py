import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

def run_drought_monitoring_pipeline():
    """
    Process an automated Climate Risk Pipeline to compute the Rainfall Anomaly Index (RAI)
    and isolate severe meteorological drought anomalies across agricultural zones.
    """
    print("Initializing Spatial Climate Monitoring Engine...")

    ## 1. Generate 20-Year Historical Climate Dataset (2005 - 2025)
    np.random.seed(55)
    lgas = ["Asa", "Baruten", "Edu", "Ilorin South", "Moro"]
    years = list(range(2005, 2026))
    drought_years = [2015, 2021]

    data = []
    for year in years:
        for lga in lgas:
            if year in drought_years:
                annual_rainfall = np.random.uniform(550, 750)
            else:
                annual_rainfall = np.random.uniform(950, 1400)

            data.append({
                "Year": year,
                "LGA": lga,
                "Total_Rainfall_mm": round(annual_rainfall, 2)
            })

    df_climate = pd.DataFrame(data)

    ## 2. Create Long-Term Historical Mean Rainfall per LGA using transform()
    lga_means = df_climate.groupby("LGA")["Total_Rainfall_mm"].transform("mean")

    ## 3. Compute the Rainfall Anomaly Index (RAI) Matrix
    df_climate["RAI"] = ((df_climate["Total_Rainfall_mm"] - lga_means) / lga_means) * 10

    # 4. Seperate Extreme Climate Vulnerabilities (RAI < -2)
    extreme_droughts = df_climate[df_climate["RAI"] < -2]

    print("\n--- CRITICAL DROUGHT DETECTOR REPORT (RAI < -2) ---")
    print(extreme_droughts.sort_values(by="Year").to_string(index=False))

    # 5. Show Historical Anomaly Time-Series Visual Timeline
    plt.figure(figsize=(10, 6))
    for lga in df_climate["LGA"].unique():
        lga_df = df_climate[df_climate["LGA"] == lga]
        plt.plot(lga_df["Year"], lga_df["RAI"], marker='o', label=lga)

    plt.axhline(y=-2, color='red', linestyle='--', linewidth=2, label="Extreme Drought Threshold")
    plt.title("Historical Climate Anomaly Index Tracking (Kwara State)", fontsize=12, pad=15)
    plt.xlabel("Year Timeline")
    plt.ylabel("Rainfall Anomaly Index (RAI) Score")
    plt.grid(True, alpha=0.3)
    plt.legend()
    plt.show()

if __name__ == "__main__":
    run_drought_monitoring_pipeline()